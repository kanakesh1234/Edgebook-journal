import { NextResponse } from "next/server";

export const dynamic = "force-dynamic";

const BASH_SCRIPT = `#!/usr/bin/env bash
# ==============================================================================
# EdgeBook Terminal AI Bridge for Google Gemini Pro & agy
# ==============================================================================
set -e

DIR="\${1:-edgebook-journal}"

echo "⚡ [EdgeBook] Setting up local AI workspace in ./\$DIR..."
mkdir -p "\$DIR/trades" "\$DIR/journals" "\$DIR/playbooks" "\$DIR/reports"

cat << 'EOF' > "\$DIR/GEMINI.md"
# EdgeBook Trading Workspace (Gemini Pro & agy)

You are the trader's elite performance analyst and private trading coach.
This workspace contains trading journal data bridged directly from EdgeBook.

## Workspace Layout
- \`trades/\`: Trade logs with PnL, R-multiples, sessions, entries, and exits.
- \`journals/\`: Qualitative daily notes on mindset, emotional states, and psychology.
- \`playbooks/\`: Trading plans, rules, and setup criteria.
- \`reports/\`: Persistent analysis reports, audits, and weekly reviews.

## Core Directives
1. Compute exact mathematical metrics (win rate, profit factor, R:R) using python or shell commands. Never estimate.
2. Cross-reference emotional notes in \`journals/\` against trade outcomes in \`trades/\` to identify psychological triggers.
3. Compare actual executions against rules in \`playbooks/\` to flag FOMO, revenge trading, or rule violations.
4. Save every comprehensive audit and review into \`reports/YYYY-MM-DD-audit.md\` so future sessions can track progress.
EOF

cat << 'EOF' > "\$DIR/reports/README.md"
# Analysis & Audit Reports

Reports generated by \`agy\` are saved in this directory.
When running future audits, \`agy\` references past reports to track behavioral improvements.
EOF

echo "✅ [EdgeBook] Workspace ready in ./\$DIR!"
echo ""
echo "To begin your private AI analysis with Gemini Pro:"
echo "  cd \$DIR"
echo "  agy"
echo ""
`;

export async function GET(request: Request) {
  const ua = request.headers.get("user-agent") || "";
  const isCurl = ua.toLowerCase().includes("curl");

  if (isCurl || new URL(request.url).searchParams.get("format") === "sh") {
    return new NextResponse(BASH_SCRIPT, {
      status: 200,
      headers: {
        "Content-Type": "text/x-shellscript; charset=utf-8",
        "Cache-Control": "no-store",
      },
    });
  }

  return NextResponse.json({
    name: "edgebook-bridge",
    command: "npx edgebook sync && cd edgebook-journal && agy",
    docs: "Bridges Google Drive trading data directly to a local terminal folder for agy and Gemini Pro.",
    targetDir: "edgebook-journal",
    reportsDir: "edgebook-journal/reports",
  });
}
