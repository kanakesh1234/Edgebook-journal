// Scans src/app and emits a route table with the same layout/template nesting Next uses.
// Shared layouts are imported ONCE so React keeps their state across navigations, like Next.
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "../..");
const app = path.join(root, "src/app");
const pages = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) { if (f.name !== "api") walk(p); }
    else if (f.name === "page.tsx") pages.push(dir);
  }
})(app);

const rel = (d) => path.relative(app, d).split(path.sep).filter(Boolean);
const spec = (d, name) => ["@/app", ...rel(d), name].join("/");
const ids = new Map(); // module specifier → identifier
const id = (s) => { if (!ids.has(s)) ids.set(s, `M${ids.size}`); return ids.get(s); };

const rows = [];
pages.sort().forEach((dir) => {
  const segs = rel(dir);
  const urlSegs = segs.filter((s) => !/^\(.*\)$/.test(s));
  const chain = [];
  let cur = app;
  const dirs = [app, ...segs.map((s) => (cur = path.join(cur, s)))];
  dirs.forEach((d, di) => {
    for (const kind of ["layout", "template"]) {
      if (di === 0 && kind === "layout") continue; // root layout renders <html>; the harness page replaces it
      if (fs.existsSync(path.join(d, kind + ".tsx"))) chain.push(id(spec(d, kind)));
    }
  });
  const pageId = id(spec(dir, "page"));
  const pattern = "^/" + urlSegs.map((s) => (s.startsWith("[") ? "([^/]+)" : s)).join("/") + "/?$";
  const names = urlSegs.filter((s) => s.startsWith("[")).map((s) => s.slice(1, -1));
  rows.push(`  { pattern: new RegExp(${JSON.stringify(pattern.replace("^//?$", "^/?$"))}), names: ${JSON.stringify(names)}, page: ${pageId} as ComponentType, chain: [${chain.join(", ")}] as ComponentType<{ children: ReactNode }>[], path: ${JSON.stringify("/" + urlSegs.join("/"))} }`);
});
let out = `// GENERATED by gen-routes.mjs — do not edit\nimport type { ComponentType, ReactNode } from "react";\n`;
for (const [s, i] of ids) out += `import ${i} from "${s}";\n`;
out += `\nexport const routes = [\n${rows.join(",\n")}\n];\n`;
fs.writeFileSync(path.join(import.meta.dirname, "routes.generated.tsx"), out);
console.log(`routes: ${pages.length}`);
